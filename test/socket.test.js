import { test } from 'node:test';
import assert from 'node:assert/strict';
import { io as client } from 'socket.io-client';
import { createApp } from '../server/index.js';
import { once } from 'node:events';

const emit = (socket, event, data) => new Promise((resolve, reject) => socket.timeout(3000).emit(event, data, (error, result) => error ? reject(error) : resolve(result)));
test('HTTP and real sockets: host authentication, join, scoring, permissions, pause and recovery', async t => {
  const runtime = createApp({ hostKey: 'teacher-test-secret' });
  runtime.http.listen(0, '127.0.0.1'); await once(runtime.http, 'listening');
  const url = `http://127.0.0.1:${runtime.http.address().port}`;
  const sockets = [];
  t.after(async () => { for (const s of sockets) s.disconnect(); await runtime.close(); });
  async function connect() { const s = client(url, { forceNew: true, reconnection: false }); sockets.push(s); await once(s, 'connect'); return s; }
  const [host, alice, bob] = await Promise.all([connect(), connect(), connect()]);
  const response = await fetch(`${url}/api/quizzes`), quizzes = await response.json();
  assert.equal(response.status, 200); assert.equal(quizzes[0].questions, undefined);
  assert.match(response.headers.get('content-security-policy'), /script-src 'self'/);
  assert.equal((await fetch(`${url}/healthz`)).status, 200);
  assert.equal((await emit(host, 'host:create', { quizId: quizzes[0].id, hostKey: 'wrong' })).ok, false);
  const created = await emit(host, 'host:create', { quizId: quizzes[0].id, hostKey: 'teacher-test-secret', duration: 60 });
  assert.equal(created.ok, true); assert.match(created.session.code, /^\d{6}$/);
  const code = created.session.code;
  const joined = await emit(alice, 'player:join', { code, nickname: 'Alice' });
  await emit(bob, 'player:join', { code, nickname: 'Bob' });
  assert.equal((await emit(alice, 'host:control', { action: 'start' })).ok, false);
  assert.equal((await emit(host, 'host:control', { action: 'start' })).ok, true);
  const room = runtime.store.get(code), player = [...room.players.values()].find(p => p.nickname === 'Alice');
  const q = player.question;
  const scored = await emit(alice, 'player:answer', { questionId: q.id, choiceId: q.choices.find(c => c.correct).id, points: 1_000_000 });
  assert.equal(scored.feedback.delta, 30); assert.equal(player.points, 30);
  assert.equal((await emit(alice, 'player:answer', { questionId: q.id, choiceId: q.choices[0].id })).ok, false);
  assert.equal((await emit(bob, 'player:join', { code, nickname: 'Alice', token: joined.session.token })).ok, false);
  const attacker = await connect();
  assert.equal((await emit(attacker, 'player:join', { code, nickname: 'Alice' })).ok, false);
  const paused = once(bob, 'room:state'); host.disconnect(); await paused;
  assert.equal(room.status, 'paused'); assert.equal(room.pausedByDisconnect, true);
  const recoveredHost = await connect();
  assert.equal((await emit(recoveredHost, 'host:resume', { code, token: 'forged' })).ok, false);
  assert.equal((await emit(recoveredHost, 'host:resume', { code, token: created.session.token })).ok, true);
  assert.equal((await emit(recoveredHost, 'host:control', { action: 'resume' })).ok, true);
  const oldPlayerGone = once(bob, 'room:state'); alice.disconnect(); await oldPlayerGone;
  assert.equal(player.connected, false);
  const resumedAlice = await connect();
  assert.equal((await emit(resumedAlice, 'player:join', { code, nickname: 'Alice', token: joined.session.token })).ok, true);
  assert.equal(player.points, 30); assert.equal(player.connected, true);
  assert.equal((await emit(recoveredHost, 'host:control', { action: 'end' })).ok, true);
  assert.equal(room.status, 'ended');
});
